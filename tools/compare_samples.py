#!/usr/bin/env python3
"""compare_samples.py
Diffs two Xeno-family DLLs and writes a markdown change report.

Usage:  python tools/compare_samples.py <old.dll> <new.dll> [-o COMPARE_REPORT.md]

Typical use after `update_sample.py` (which leaves timestamped .bak files):
    python tools/compare_samples.py sample/TEST.dll.20251109_180000.bak sample/TEST.dll
"""

import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sample_report import analyze  # noqa: E402

WORKSPACE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# strings matching these are "interesting" for the string-level diff
INTERESTING = None
import re
INTERESTING = re.compile(
    r"xeno|attach|offset|module|loadstring|bytecode|http|localhost|pipe|"
    r"hook|script|client|server|teleport|autoexec|cache|hwid|key|version", re.I)


def diff_sets(old, new):
    old_s, new_s = set(old), set(new)
    return sorted(new_s - old_s), sorted(old_s - new_s)


def section(title, added, removed, limit=60):
    L = [f"## {title}", ""]
    if not added and not removed:
        L += ["No changes.", ""]
        return L
    if added:
        L.append(f"**Added ({len(added)}):**")
        L.append("")
        L += [f"+ `{x}`" for x in added[:limit]]
        if len(added) > limit:
            L.append(f"+ ... and {len(added) - limit} more")
        L.append("")
    if removed:
        L.append(f"**Removed ({len(removed)}):**")
        L.append("")
        L += [f"- `{x}`" for x in removed[:limit]]
        if len(removed) > limit:
            L.append(f"- ... and {len(removed) - limit} more")
        L.append("")
    return L


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("-")]
    if len(args) < 2:
        sys.exit("usage: python tools/compare_samples.py <old.dll> <new.dll> [-o out.md]")
    out = (sys.argv[sys.argv.index("-o") + 1] if "-o" in sys.argv
           else os.path.join(WORKSPACE, "COMPARE_REPORT.md"))

    print(f"analyzing OLD: {args[0]}")
    old = analyze(args[0])
    print(f"analyzing NEW: {args[1]}")
    new = analyze(args[1])

    L = []
    add = L.append
    add("# COMPARE_REPORT.md — AUTO-GENERATED")
    add("")
    add("> Regenerated by `tools/compare_samples.py`. Do not edit.")
    add(f"> Generated: {datetime.datetime.now(datetime.UTC).strftime('%Y-%m-%d %H:%M:%S')} UTC")
    add("")
    add("| | OLD | NEW |")
    add("|---|---|---|")
    add(f"| File | `{os.path.basename(old['path'])}` | `{os.path.basename(new['path'])}` |")
    add(f"| Size | {old['size']:,} | {new['size']:,} |")
    add(f"| SHA-256 | `{old['sha256'][:16]}...` | `{new['sha256'][:16]}...` |")
    add(f"| PE timestamp | {old['timestamp_str']} | {new['timestamp_str']} |")
    add(f"| Version strings | {', '.join(old['versions']) or '?'} | {', '.join(new['versions']) or '?'} |")
    add(f"| Detector score | {old['detector']['score']} ({old['detector']['verdict']}) "
        f"| {new['detector']['score']} ({new['detector']['verdict']}) |")
    k_old = old["xor_key"] or "—"
    k_new = new["xor_key"] or "—"
    changed = " **(KEY CHANGED)**" if k_old != k_new else ""
    add(f"| XOR key ({old['xor_key_status']}→{new['xor_key_status']}) | `{k_old[:32]}...` "
        f"| `{k_new[:32]}...`{changed} |")
    add("")

    if old["sha256"] == new["sha256"]:
        add("**Files are identical (SHA-256 match) — no differences.**")
        add("")
    else:
        L += section("Exports", *diff_sets(old["exports"], new["exports"]))

        # imports: dll-level then function-level
        dll_add, dll_rm = diff_sets(old["imports"], new["imports"])
        L += section("Import DLLs", dll_add, dll_rm)
        fn_changes = []
        for dll in sorted(set(old["imports"]) & set(new["imports"])):
            a, r = diff_sets(old["imports"][dll], new["imports"][dll])
            fn_changes += [f"{dll}!{x}" for x in a], [f"{dll}!{x}" for x in r]
        L += section("Imported functions", fn_changes[0], fn_changes[1])

        L += section("URLs", *diff_sets(old["urls"], new["urls"]))
        L += section("Environment variables", *diff_sets(old["env_vars"], new["env_vars"]))

        # resources
        add("## Encrypted resources")
        add("")
        res_names = sorted(set(old["resources"]) | set(new["resources"]))
        if not res_names:
            add("No type-8194 resources in either sample.")
            add("")
        else:
            add("| Resource | OLD size | NEW size | Δ |")
            add("|---|---|---|---|")
            for r in res_names:
                o, n = old["resources"].get(r), new["resources"].get(r)
                os_ = f"{o['size']:,}" if o else "—"
                ns = f"{n['size']:,}" if n else "—"
                delta = ""
                if o and n:
                    dd = n["size"] - o["size"]
                    delta = f"{dd:+,}"
                add(f"| `{r}` | {os_} | {ns} | {delta} |")
            add("")
            add("| Resource | OLD payload | NEW payload |")
            add("|---|---|---|")
            for r in res_names:
                o, n = old["payloads"].get(r), new["payloads"].get(r)
                os_ = f"{o['size']:,}" if o and o["size"] else "?"
                ns = f"{n['size']:,}" if n and n["size"] else "?"
                add(f"| `{r}` | {os_} | {ns} |")
            add("")

        # string-level diff (interesting only)
        oi = [s for s in old["strings"] if INTERESTING.search(s) and len(s) < 120]
        ni = [s for s in new["strings"] if INTERESTING.search(s) and len(s) < 120]
        L += section("Interesting strings (filtered)", *diff_sets(oi, ni))

        # section sizes
        sec_changes = []
        o_sec = {s["name"]: s for s in old["sections"]}
        n_sec = {s["name"]: s for s in new["sections"]}
        for nm in sorted(set(o_sec) | set(n_sec)):
            o, n = o_sec.get(nm), n_sec.get(nm)
            if not o:
                sec_changes.append(f"section `{nm}` added ({n['vsize']:,} bytes)")
            elif not n:
                sec_changes.append(f"section `{nm}` removed")
            elif o["vsize"] != n["vsize"]:
                sec_changes.append(
                    f"section `{nm}` vsize {o['vsize']:,} -> {n['vsize']:,} "
                    f"({n['vsize'] - o['vsize']:+,})")
        L += section("Section layout", sec_changes, [])

    open(out, "w", encoding="utf-8").write("\n".join(L))
    print(f"[OK] comparison written -> {out}")


if __name__ == "__main__":
    main()
